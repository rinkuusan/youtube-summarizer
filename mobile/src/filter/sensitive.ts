import { normalizeForSearch } from '../utils/normalize';

/**
 * 画像をぼかすかどうかの判定。
 *
 * 正直に言っておくと、これは画像の中身を見ていない。端末で画像認識を回すには
 * NSFW 判定モデルを積む必要があり、アプリの重さに見合わない。
 *
 * 代わりに 5ch 側の慣習を使う。グロ画像を貼る側は、ほぼ必ず本文かスレタイに
 * 「グロ注意」「閲覧注意」のような警告を書く。この警告を拾う方が、貧弱な
 * 画像分類より実際には当たる。
 *
 * ただし取りこぼしは必ず出る。警告を書かずに貼られたら素通しする。
 * それが困る場合のために、設定で「常にぼかす」を選べるようにしてある。
 */

/**
 * 警告の語。話題語ではなく「警告として書かれる語」に寄せる。
 * 「死体」のような話題語まで入れると、ニュース系のスレが軒並みぼけて使い物にならない。
 */
const WARNING_PATTERNS = [
  '閲覧注意',
  'えつらんちゅうい',
  'グロ',
  'ぐろ',
  'ゴア',
  '心臓の弱い',
  '心臓が弱い',
  'トラウマ',
  '要注意画像',
  '注意画像',
  '虫注意',
  '蟲注意',
  'リョナ',
  'デスヨナ',
  '苦手な人',
  '苦手な方',
  '覚悟して',
  'ショッキング',
].map((w) => normalizeForSearch(w));

/**
 * 本文やスレタイに警告が書かれているか。
 *
 * 判定対象は「そのレスの本文」と「スレタイ」。スレタイを含めるのは、
 * グロ画像スレは 1 レス目やタイトルにだけ警告を書き、以降のレスには
 * 何も書かないことが多いため。
 */
export function looksSensitive(text: string, threadTitle?: string | null): boolean {
  const hay = normalizeForSearch(`${text}\n${threadTitle ?? ''}`);
  return WARNING_PATTERNS.some((w) => hay.includes(w));
}
